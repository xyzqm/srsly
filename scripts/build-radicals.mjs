import { readFile } from 'fs/promises';
import path from 'path';
import { fileURLToPath } from 'url';
import { emitData } from './lib/emitData.mjs';

/**
 * Han character decomposition — 休 = 亻 (person) + 木 (tree).
 *
 * SOURCE: makemeahanzi's dictionary.txt, itself derived from Unihan and CJKlib, under the
 * LGPL v3. See scripts/data/ATTRIBUTION.md — this is the one dataset srsly ships to the
 * client rather than consuming at build time, so the obligation travels with the emitted
 * file and is recorded there.
 *
 * The canonical alternative, CHISE/cjkvi `ids.txt`, is GPLv2. That is why it is not used:
 * a copyleft obligation on a shipped data file is a different proposition from LGPL, and
 * this repo has consistently declined sources whose terms do not fit (see the CEFRLex note
 * in CLAUDE.md).
 *
 * WHAT IS EMITTED, AND WHY IT IS SMALL. The raw file is 2.5 MB over 9,574 characters, which
 * is far more than a learner of HSK/JLPT vocabulary will ever look up. The build keeps only
 * characters that appear in those two graded vocabularies, then TRANSITIVELY adds every
 * component those characters decompose into — otherwise a kept character could reference a
 * component with no gloss, and the popup would show a bare shape with nothing to say about it.
 */

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.join(HERE, 'data', 'makemeahanzi-dictionary.txt');

/** Ideographic Description Characters — the layout operators inside an IDS string. */
const IDC = /[⿰-⿻]/g;
const HAN = /[一-鿿㐀-䶿]/;

/** First sense only. A component gloss is a label, not a dictionary entry. */
function shortGloss(def) {
  if (!def) return '';
  return def.split(/[;,]/)[0].trim().replace(/^to\s+/, '');
}

async function main() {
  const raw = await readFile(SRC, 'utf8');
  const byChar = new Map();
  for (const line of raw.split('\n')) {
    if (!line.trim()) continue;
    try {
      const d = JSON.parse(line);
      byChar.set(d.character, d);
    } catch { /* skip malformed line */ }
  }

  // The characters worth shipping: everything used by the graded vocabularies.
  const [{ HSK_VOCAB }, { JLPT_VOCAB }] = await Promise.all([
    import('../lib/data/hsk-vocab.ts').catch(() => import('../lib/data/hsk-vocab.json', { with: { type: 'json' } }).then(m => ({ HSK_VOCAB: m.default }))),
    import('../lib/data/jlpt-vocab.ts').catch(() => import('../lib/data/jlpt-vocab.json', { with: { type: 'json' } }).then(m => ({ JLPT_VOCAB: m.default }))),
  ]);

  const wanted = new Set();
  for (const word of [...Object.keys(HSK_VOCAB), ...Object.keys(JLPT_VOCAB)]) {
    for (const ch of word) if (HAN.test(ch)) wanted.add(ch);
  }
  const seedCount = wanted.size;

  // Transitively pull in components, so every part a kept entry names can be explained.
  const queue = [...wanted];
  while (queue.length) {
    const ch = queue.pop();
    const entry = byChar.get(ch);
    if (!entry?.decomposition) continue;
    for (const part of entry.decomposition.replace(IDC, '')) {
      if (part === ch || wanted.has(part)) continue;
      if (!byChar.has(part)) continue;      // unencoded placeholder (①②…) — nothing to say
      wanted.add(part);
      queue.push(part);
    }
  }

  const out = {};
  let withHint = 0;
  for (const ch of [...wanted].sort()) {
    const e = byChar.get(ch);
    if (!e) continue;
    // Components, in reading order, minus the layout operators and anything unencoded.
    const parts = [...(e.decomposition ?? '').replace(IDC, '')]
      .filter(p => p !== ch && byChar.has(p));
    const gloss = shortGloss(e.definition);
    // A character that decomposes to nothing (or only to itself) is a primitive: still worth
    // an entry, because it is the thing OTHER characters decompose into.
    const rec = { g: gloss };
    if (parts.length) rec.p = parts.join('');
    if (e.radical && e.radical !== ch) rec.r = e.radical;
    if (e.etymology?.hint) { rec.h = e.etymology.hint.replace(/ /g, ' ').trim(); withHint++; }
    if (e.etymology?.type) rec.t = e.etymology.type;
    if (e.etymology?.phonetic) rec.ph = e.etymology.phonetic;
    if (e.etymology?.semantic) rec.se = e.etymology.semantic;
    out[ch] = rec;
  }

  const tsPath = path.join(HERE, '..', 'lib', 'data', 'han-decomp.ts');
  await emitData(
    tsPath,
    'HAN_DECOMP',
    'Record<string, { g: string; p?: string; r?: string; h?: string; t?: string; ph?: string; se?: string }>',
    out,
    `// Auto-generated by scripts/build-radicals.mjs — DO NOT EDIT BY HAND.
// Han character decomposition for the Chinese and Japanese readers.
//   g  short gloss          p  component characters, in reading order
//   r  radical              h  human-readable etymology hint
//   t  etymology type (ideographic | pictophonetic | pictographic)
//   ph phonetic component   se semantic component  (pictophonetic only)
//
// Derived from makemeahanzi's dictionary.txt (Unihan + CJKlib), LGPL v3 — see
// scripts/data/ATTRIBUTION.md. Scoped to characters used by HSK and JLPT vocabulary plus,
// transitively, every component those characters are built from.`,
  );

  const bytes = JSON.stringify(out).length;
  console.log(`[radicals] ${seedCount} characters from HSK+JLPT, ${Object.keys(out).length} after pulling in components`);
  console.log(`[radicals] ${withHint} carry an etymology hint · ${(bytes / 1024).toFixed(0)} kB emitted`);
}

main().catch(e => { console.error(e); process.exit(1); });
